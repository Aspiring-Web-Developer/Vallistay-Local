// Helper to calculate nights between 2 dates
export function calculateNights(checkInStr, checkOutStr) {
  if (!checkInStr || !checkOutStr) return 0;
  const d1 = new Date(checkInStr);
  const d2 = new Date(checkOutStr);
  const diffTime = d2.getTime() - d1.getTime();
  const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));
  return diffDays > 0 ? diffDays : 0;
}

// Smart availability suggestions based on current occupants checkouts
export function getUpcomingCheckoutSuggestions(rooms = []) {
  const occupiedRooms = rooms.filter((r) => r.currentBooking && r.currentBooking.checkOut);
  return occupiedRooms.map((r) => {
    const checkOutDate = r.currentBooking.checkOut;
    const coDateObj = new Date(checkOutDate);
    const threeDaysAfter = new Date(coDateObj);
    threeDaysAfter.setDate(coDateObj.getDate() + 3);

    const fmt = (d) => {
      try {
        return d.toISOString().split("T")[0];
      } catch {
        return checkOutDate;
      }
    };

    return {
      roomNumber: r.number,
      guestName: r.currentBooking.customerName,
      checkoutDate: checkOutDate,
      checkoutDisplay: r.currentBooking.checkoutLabel || checkOutDate,
      suggestedCheckIn: fmt(coDateObj),
      suggestedCheckOut: fmt(threeDaysAfter),
      nights: 3,
      note: `Checkout on ${r.currentBooking.checkoutLabel || checkOutDate} → Ready from ${fmt(coDateObj)} (+3 nights)`,
    };
  });
}

